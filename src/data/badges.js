import { getLevelInfo } from '../utils/xp'

const countProgress = (key, target) => (game) => ({
  current: Math.min(Number(game.counts?.[key]) || 0, target),
  target,
  available: true,
})

const streakProgress = (target) => (game) => ({
  current: Math.min(Number(game.streak) || 0, target),
  target,
  available: true,
})

const levelProgress = (target) => (game) => ({
  current: Math.min(getLevelInfo(Number(game.totalXP) || 0).level, target),
  target,
  available: true,
})

